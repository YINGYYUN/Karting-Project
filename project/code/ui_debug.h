/*********************************************************************************************************************
 * 板载调试页（只读仪表，多视图）
 *
 * 与 ui_menu.c 的分工：
 *   ui_menu.c  —— 主菜单列表 / 参数编辑（会写参数、会改运行状态）
 *   ui_debug.c —— 只读诊断视图；唯一的写操作是 IMU 视图里的"yaw 归零"
 *
 * 为什么单独一个文件：ui_menu.c 已经 1100 行且职责是"列表+编辑引擎"；本页是"多视图仪表"，
 * 绘制节奏（200 ms 定时刷新）和按键语义（K3/K4 切视图）都与列表不同，混在一起两边都难读。
 *
 * 按键：K3/K4 切视图，K1 执行本视图动作（仅 IMU 有），K2 返回主菜单。
 ********************************************************************************************************************/
#ifndef _UI_DEBUG_H
#define _UI_DEBUG_H

#include "zf_common_typedef.h"

void  ui_debug_enter  (void);                       /* 进页：先到"视图选择列表" */
void  ui_debug_move   (int8 dir);                   /* K1/K2：列表里移光标；详情页无动作 */
void  ui_debug_action (void);                       /* K3：列表里=进入该视图；详情页=本视图动作 */
uint8 ui_debug_back   (void);                       /* K4：1=已退回列表；0=已在列表，请回主菜单 */
void  ui_debug_tick   (void);                       /* 10 ms 调用，内部限频刷新数值 */

#endif
