/*******************************************************************************
遥控（目前对应 HotRc 手持枪式遥控器）

数据来源：逐飞 UART 接收机（SBUS 帧，6 通道），由 10ms 中断解析
          （见 zf_device_uart_receiver.c / cm7_0_isr.c）
本模块的职责：把"原始通道值"换算成有物理含义的指令，并提供一个主菜单页面
*******************************************************************************/


#ifndef __REMOTE_CRTL_H__
#define __REMOTE_CRTL_H__


#include "zf_common_headfile.h"


/**********************************************************/
/*[S] 通道分配 [S]----------------------------------------*/
/**********************************************************/

#define RC_CH_STEER             (0)             // CH1 → 方向盘指令
#define RC_CH_THROTTLE          (1)             // CH2 → 前后油门


/**********************************************************/
/*----------------------------------------[E] 通道分配 [E]*/
/**********************************************************/


/**********************************************************/
/*[S] 标定值 [S]------------------------------------------*/
/**********************************************************/

// 请注意，微调按键会影响CH1、CH2中位值

// CH1 方向盘：中位 992，两端满幅 192 / 1792
#define RC_STEER_MID            (992)
#define RC_STEER_MIN            (192)
#define RC_STEER_MAX            (1792)

// CH2 油门：静止约 992（实测在 988/990/992 跳变），两端满幅 192 / 1792
#define RC_THR_MID              (992)
#define RC_THR_MIN              (192)
#define RC_THR_MAX              (1792)

// 开关档位原始值：CH3 / CH5 / CH6 为两态（低 / 高），CH4 为三档（低 / 中 / 高）
// 其中 CH5 被用作急停：拨到高位（RC_Sw5 == 1）即急停
#define RC_SW_VAL_LOW           (192)
#define RC_SW_VAL_MID           (992)
#define RC_SW_VAL_HIGH          (1792)

/**********************************************************/
/*----------------------------------------[E] 标定值 [E]--*/
/**********************************************************/


/**********************************************************/
/*[S] 换算参数 [S]----------------------------------------*/
/**********************************************************/

// 方向盘指令的幅值上限（度）。与舵机闭环共用"向右为正"的约定，
// 复用舵机的行程角，控制器那边还有软限位兜底
#define RC_STEER_LIMIT_DEG      (SERVO_LIMIT_DEG)

// 方向盘极性：+1 = 原始值增大的方向为"向右"；实测方向相反就改成 -1
#define RC_STEER_DIR_SIGN       (+1)

// 油门中位死区（原始计数）：|CH2 - RC_THR_MID| 不超过它就算 0
// 即 990 ± 8 → 982 ~ 1002 全部当"没给油"，把静止抖动压掉
#define RC_THR_DEADBAND         (8)

// 后轮速度目标的上限（单位：rps，与 Motor_Crtl 同口径）
// 油门 ±1.0 线性映射到这两个值：前进为正、后退为负
// 取 1.0 rps 是为了保住原本的车速（原"每 10ms 编码器计数"口径的 ±20 ≈ 1.08 rps）
#define RC_THR_TARGET_FWD       ( 1.0f)
#define RC_THR_TARGET_REV       (-1.0f)

/**********************************************************/
/*----------------------------------------[E] 换算参数 [E]*/
/**********************************************************/


/**********************************************************/
/*[S] 闭环介入状态 [S]------------------------------------*/
/**********************************************************/

// 进页面即进入 STANDBY（双闭环使能、目标 0）；只有接收机状态正常（ST = 1）时
// 才允许按下确认键让遥控接管目标；ST 掉到 0 会掉进 FAILSAFE 并锁住，不会自动恢复
#define RC_ENGAGE_OFF           (0)     // 全部失能、目标 0（离开遥控页面后的状态）
#define RC_ENGAGE_STANDBY       (1)     // 双闭环使能、目标 0（进页面后的默认状态，遥控尚未接管）
#define RC_ENGAGE_ON            (2)     // 双闭环使能 + 遥控设置目标
#define RC_ENGAGE_FAILSAFE      (3)     // 失控挂起：舵机失能；后轮**保持使能**、目标 0（主动刹停）
// 急停（CH5 原始值为高位，即 RC_Sw5 == 1 时触发）：后轮保持使能、目标 0（主动刹停）；
// 舵机保持急停前的转向、不再跟随 CH1。进入后**锁存**，遥控彻底失效；
// 恢复 = 先把 CH5 拨回低位，再在板子上重新按确认键
#define RC_ENGAGE_ESTOP         (4)

/**********************************************************/
/*----------------------------------------[E] 闭环介入状态 [E]*/
/**********************************************************/


/**********************************************************/
/*[S] 对外数据 [S]----------------------------------------*/
/**********************************************************/

// 以下都由 Remote_Crtl_Update() 刷新
extern volatile uint16 RC_Raw_Ch1;                  // CH1 原始值（标定/显示用）
extern volatile uint16 RC_Raw_Ch2;                  // CH2 原始值
extern volatile float  RC_Steer_Deg;                // 方向盘指令角（度，向右为正）
extern volatile float  RC_Throttle;                 // 归一化油门 -1.0 ~ +1.0（前进为正）
extern volatile uint8  RC_Sw3;                      // CH3 两态 0/1
extern volatile int8   RC_Sw4;                      // CH4 三档 -1 / 0 / +1
extern volatile uint8  RC_Sw5;                      // CH5 两态 0/1
extern volatile uint8  RC_Sw6;                      // CH6 两态 0/1
extern volatile uint8  RC_Online;                   // 1 = 接收机报告状态正常（未失控）
extern volatile uint8  RC_Engage;                   // 闭环介入状态，取 RC_ENGAGE_OFF / STANDBY / ON / FAILSAFE / ESTOP

/**********************************************************/
/*----------------------------------------[E] 对外数据 [E]*/
/**********************************************************/


/**********************************************************/
/*[S] 接口 [S]--------------------------------------------*/
/**********************************************************/

// 从接收机快照换算一次（本模块不主动调用驱动，只读 uart_receiver 快照）
void    Remote_Crtl_Update  (void);
// 跑一次介入状态机并写目标（遥控页面每圈调用；调用前先 Update 一次）
void    Remote_Crtl_Apply   (void);
// 解除介入：双闭环失能、目标清零（离开遥控页面时调用）
void    Remote_Crtl_Release (void);
// 主菜单里的遥控页面
int     Remote_Crtl_Page    (void);

/**********************************************************/
/*----------------------------------------[E] 接口 [E]----*/
/**********************************************************/


#endif
