/**********************************************************/
/*[S] 默认参数 [S]----------------------------------------*/
/**********************************************************/

/* 控制周期，必须与调用它的 PIT 中断一致（当前 10ms） */
#define MOTOR_CRTL_T_S              (0.01f)

/* ★ 待标定：前馈线性项 1/K（目标单位 / 输出单位） */
#define MOTOR_CRTL_INV_K_DEFAULT    (0.0f)
/* ★ 待标定：摩擦截距 u0（输出单位） */
#define MOTOR_CRTL_U0_DEFAULT       (0.0f)
/* ★ 待标定：比例增益 k_v */
#define MOTOR_CRTL_K_V_DEFAULT      (0.0f)
/* ★ 待标定：积分增益 k_z */
#define MOTOR_CRTL_K_Z_DEFAULT      (0.0f)

/* 目标变化率上限（单位/秒），0 = 关闭斜坡 */
#define MOTOR_CRTL_SLEW_DEFAULT     (0.0f)
/* 目标跳变超过它就清积分，0 = 关闭该保护 */
#define MOTOR_CRTL_INT_CLR_STEP     (0.0f)
/* 积分状态限幅（防裹死），0 = 不限 */
#define MOTOR_CRTL_Z_MAX            (0.0f)
/* 目标绝对值上限（与调试页滑条量程一致即可） */
#define MOTOR_CRTL_TARGET_MAX       (800.0f)
/* 输出限幅（沿用原工程 ±4000） */
#define MOTOR_CRTL_OUT_MAX          (4000.0f)
/* 前馈摩擦截距的死区：|r| 不超过它就不加 u0，0 = 只排除 r=0 */
#define MOTOR_CRTL_FF_DEADBAND      (0.0f)

/* 主节拍周期 ms（必须与 PIT 一致），编码器脱落计时用 */
#define MOTOR_CRTL_TICK_MS          (10)

/* ---- 心跳门限 ----
   由"正在监督电机运行的那个循环"每圈调 Motor_Crtl_HB_Feed()；
   10ms 中断里判定，超过 MOTOR_CRTL_HB_TIMEOUT_MS 没喂 -> 门控不过、输出 0。
   ★ 喂心跳的必须是**真正在转的那个循环**：电机只在 MOTOR-PID 页里使能，
     所以只喂在该页的两处循环；Menu_Show() 的循环不需要（不进页面时电机本来就是关的）。 */
#define MOTOR_CRTL_HB_TIMEOUT_MS    (200)

/* ---- 编码器脱落 / 堵转保护 ----
   判据只能用"指令侧"的量：编码器坏了就没有转速可读，不能拿转速当条件。
   |out| 超过 MOTOR_CRTL_ENC_LOST_OUT、且本路编码器连续 MOTOR_CRTL_ENC_LOST_MS
   一点不动（单拍增量为 0）-> 判定反馈失效，锁存停机（Motor_Crtl_Reset 才清）。
   1800 的依据：反馈一旦失效，误差恒为 r，积分会把输出快速顶到限幅（4000），
   很快突破这个值；而正常闭环跟踪时 |out| 一般远低于它。
   副作用：真被外力堵住的轮子同样满足判据 -> 一起停（两者观测量分不开，宁停勿冲）。 */
#define MOTOR_CRTL_ENC_LOST_OUT     (1800.0f)
#define MOTOR_CRTL_ENC_LOST_MS      (500)

