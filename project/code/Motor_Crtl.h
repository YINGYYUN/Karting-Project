// 初始化（清状态 + 电机输出归零）
void    Motor_Crtl_Init     (void);
// 复位：清积分、斜坡状态与目标（进/出调试页时用）
void    Motor_Crtl_Reset    (void);
// 10ms 主节拍：门控 -> 取反馈 -> 两路控制 -> 写输出
void    Motor_Crtl_Tick     (void);
// 单路控制计算（通用函数写法，与 PID 基础函数同一风格）
void    Motor_Crtl_Update   (Motor_Crtl_t *p);

