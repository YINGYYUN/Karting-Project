// 后轮速度闭环结构体
typedef struct
{
    /* --- 参数（可单独改，便于后续按实测回填） --- */
    uint8   motor_id;           // Motor_Set() 用的电机号
    float   inv_K;              // 前馈线性项 1/K
    float   u0;                 // 前馈摩擦截距
    float   k_v;                // 比例增益
    float   k_z;                // 积分增益
    float   target_max;         // 目标绝对值上限
    float   out_max;            // 输出限幅

    /* --- 运行状态 --- */
    float   target;             // 目标（由调试页/上层写）
    float   target_app;         // 斜坡之后的实际目标
    float   actual;             // 实测（本周期编码器增量）
    float   e;                  // 本拍误差
    float   z;                  // 积分状态
    float   u_ff;               // 前馈分量
    float   u_cmd;              // 限幅前的控制器输出
    float   out;                // 本拍真正给出去的输出
    uint8   sat;                // 1 = 本拍饱和（积分被冻结）
    uint8   enabled;            // 1 = 本拍闭环在跑
    uint32  zero_ms;            // 编码器脱落计时：已连续多少 ms "在出力但编码器不动"
    uint8   enc_fault;          // 1 = 本路因编码器脱落/堵转停机（锁存，Reset 才清）
} Motor_Crtl_t;

// 两路实例
extern Motor_Crtl_t     Motor_LR_Crtl;      // 左后轮
extern Motor_Crtl_t     Motor_RR_Crtl;      // 右后轮

// 闭环总使能（0 = 两路输出强制 0，并清积分与斜坡状态）
extern volatile uint8   Motor_Crtl_Enable;

